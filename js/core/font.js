  var CHARS = Object.keys(G);
  var CELL = 8, COLS = 16;
  var baseSheet = null, sheets = {}, widths = {}, index = {};
  var COLOR_CODES = { '0': '#000000', '1': '#0000AA', '2': '#00AA00', '3': '#00AAAA', '4': '#AA0000', '5': '#AA00AA', '6': '#FFAA00', '7': '#AAAAAA', '8': '#555555', '9': '#5555FF', 'a': '#55FF55', 'b': '#55FFFF', 'c': '#FF5555', 'd': '#FF55FF', 'e': '#FFFF55', 'f': '#FFFFFF' };

  function buildBase() {
    var rows = Math.ceil(CHARS.length / COLS);
    var c = document.createElement('canvas'); c.width = COLS * CELL; c.height = rows * CELL;
    var ctx = c.getContext('2d'); ctx.fillStyle = '#fff';
    for (var i = 0; i < CHARS.length; i++) {
      var ch = CHARS[i], rowsG = G[ch]; index[ch] = i; widths[ch] = rowsG[0].length;
      var cx = (i % COLS) * CELL, cy = Math.floor(i / COLS) * CELL;
      for (var y = 0; y < rowsG.length; y++) for (var x = 0; x < rowsG[y].length; x++) if (rowsG[y][x] === '#') ctx.fillRect(cx + x, cy + y, 1, 1);
    }
    baseSheet = c;
  }
  function sheetFor(color) {
    if (sheets[color]) return sheets[color];
    if (!baseSheet) buildBase();
    var c = document.createElement('canvas'); c.width = baseSheet.width; c.height = baseSheet.height;
    var ctx = c.getContext('2d'); ctx.drawImage(baseSheet, 0, 0);
    ctx.globalCompositeOperation = 'source-in'; ctx.fillStyle = color; ctx.fillRect(0, 0, c.width, c.height);
    sheets[color] = c; return c;
  }
  function parseColor(col) {
    if (Array.isArray(col)) return col;
    if (typeof col === 'number') return [(col >> 16) & 255, (col >> 8) & 255, col & 255];
    if (typeof col === 'string' && col[0] === '#') { var h = col.slice(1); if (h.length === 3) h = h[0] + h[0] + h[1] + h[1] + h[2] + h[2]; var n = parseInt(h, 16); return [(n >> 16) & 255, (n >> 8) & 255, n & 255]; }
    return [255, 255, 255];
  }
  function toCss(c) { return 'rgb(' + (c[0] | 0) + ',' + (c[1] | 0) + ',' + (c[2] | 0) + ')'; }
  function shadowOf(c) { return [c[0] >> 2, c[1] >> 2, c[2] >> 2]; }

  function width(text) {
    if (!baseSheet) buildBase();
    var w = 0;
    for (var i = 0; i < text.length; i++) {
      var ch = text[i];
      if (ch === '§' && i + 1 < text.length) { i++; continue; }
      w += (widths[ch] !== undefined ? widths[ch] : 5) + 1;
    }
    return w;
  }
  // Draw text at GUI coords (ctx already scaled). Supports §x color codes.
  function draw(ctx, text, x, y, color, shadow) {
    if (!baseSheet) buildBase();
    var base = parseColor(color === undefined ? '#ffffff' : color);
    if (shadow === undefined) shadow = true;
    var cur = base, cx = x;
    var passes = shadow ? [[1, true], [0, false]] : [[0, false]];
    for (var p = 0; p < passes.length; p++) {
      var off = passes[p][0], isShadow = passes[p][1];
      cur = base; cx = x;
      for (var i = 0; i < text.length; i++) {
        var ch = text[i];
        if (ch === '§' && i + 1 < text.length) { var code = text[i + 1].toLowerCase(); i++; if (code === 'r') cur = base; else if (COLOR_CODES[code]) cur = parseColor(COLOR_CODES[code]); continue; }
        var idx = index[ch]; if (idx === undefined) { idx = index['?']; }
        var w = widths[ch] !== undefined ? widths[ch] : 5;
        var sheet = sheetFor(toCss(isShadow ? shadowOf(cur) : cur));
        ctx.drawImage(sheet, (idx % COLS) * CELL, Math.floor(idx / COLS) * CELL, w, CELL, cx + off, y + off, w, CELL);
        cx += w + 1;
      }
    }
    return cx - x;
  }
  function drawCentered(ctx, text, cx, y, color, shadow) { return draw(ctx, text, Math.floor(cx - width(text) / 2), y, color, shadow); }
  function drawRight(ctx, text, rx, y, color, shadow) { return draw(ctx, text, rx - width(text), y, color, shadow); }
  // trim text to fit maxWidth with ellipsis
  function fit(text, maxW) { if (width(text) <= maxW) return text; while (text.length && width(text + '...') > maxW) text = text.slice(0, -1); return text + '...'; }
  function wrap(text, maxW) {
    var words = text.split(' '), lines = [], cur = '';
    for (var i = 0; i < words.length; i++) { var t = cur ? cur + ' ' + words[i] : words[i]; if (width(t) > maxW && cur) { lines.push(cur); cur = words[i]; } else cur = t; }
    if (cur) lines.push(cur); return lines;
  }
